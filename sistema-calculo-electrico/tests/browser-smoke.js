async (page) => {
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.reload();
  await page.getByRole('button',{name:'2 · Cargas 14'}).click();
  await page.locator('#input-excel').setInputFiles('C:/Users/los olivos/Desktop/EMPRESA CONECTATECH 2026/1. Ingenieria albamar/11. Proyecto Energia/Calculo de consumo Sala El Tabo.xlsx');
  await page.locator('#excel-apply').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.getElementById('excel-apply').disabled);
  const summary=await page.locator('#excel-summary').textContent();
  if(!summary.includes('14 partidas')||!summary.includes('11.080 W'))throw Error(summary);
  const preview=await page.locator('#excel-preview').textContent();
  if(!preview.includes('Hoja1!5')||!preview.includes('Hoja1!23'))throw Error('Source rows shifted');
  await page.locator('#excel-apply').click();
  if(await page.locator('#cargas-body tr').count()!==14)throw Error('Lost rows');
  const bounds=async selector=>page.locator(selector).evaluate(svg=>{
    const v=svg.viewBox.baseVal;
    return [...svg.querySelectorAll('text')].map(t=>({text:t.textContent,b:t.getBBox()})).filter(({b})=>b.x<0||b.y<0||b.x+b.width>v.width||b.y+b.height>v.height).map(t=>t.text);
  });
  await page.getByRole('button',{name:'4 · Diagrama unifilar'}).click();
  let clipped=await bounds('#diagrama-wrap svg');if(clipped.length)throw Error('Clipped unifilar: '+clipped.join(';'));
  await page.locator('#diagrama-wrap-toolbar [data-view="fit"]').click();
  await page.locator('#diagrama-wrap').screenshot({path:'output/playwright/unifilar-completo.png'});
  await page.locator('#diagrama-wrap-toolbar [data-view="real"]').click();
  const scaled=await page.locator('#diagrama-wrap svg').evaluate(s=>parseFloat(s.style.width)===s.viewBox.baseVal.width);
  if(!scaled)throw Error('100% zoom failed');
  await page.locator('#diagrama-wrap').screenshot({path:'output/playwright/unifilar-detalle.png'});
  const [d1]=await Promise.all([page.waitForEvent('download'),page.locator('#btn-dxf').click()]);
  await d1.saveAs('sistema-calculo-electrico/output/ui-unifilar.dxf');
  await page.getByRole('button',{name:'5 · Tablero eléctrico'}).click();
  clipped=await bounds('#tablero-dibujo-wrap svg');if(clipped.length)throw Error('Clipped tablero: '+clipped.join(';'));
  await page.locator('#tablero-dibujo-wrap').screenshot({path:'output/playwright/tablero-detalle.png'});
  const [d2]=await Promise.all([page.waitForEvent('download'),page.locator('#btn-dxf-tablero').click()]);
  await d2.saveAs('sistema-calculo-electrico/output/ui-tablero.dxf');
  await page.getByRole('button',{name:'1 · Proyecto'}).click();
  await page.locator('#p-ups-circuito').selectOption('5');
  await page.getByRole('button',{name:'4 · Diagrama unifilar'}).click();
  if(!(await page.locator('#diagrama-wrap svg').textContent()).includes('Alimentada desde C5'))throw Error('UPS circuit not updated');
  await page.getByRole('button',{name:'1 · Proyecto'}).click();
  await page.locator('#p-gen-hab').uncheck();
  await page.locator('#p-ups-hab').uncheck();
  await page.getByRole('button',{name:'5 · Tablero eléctrico'}).click();
  const txt=await page.locator('#tablero-dibujo-wrap svg').textContent();
  if(txt.includes('Generador externo')||txt.includes('UPS 2'))throw Error('Disabled equipment visible');
  await page.getByRole('button',{name:'1 · Proyecto'}).click();
  await page.locator('#p-gen-hab').check();await page.locator('#p-ups-hab').check();
  await page.locator('#p-ups-circuito').selectOption('2');
  await page.getByRole('button',{name:'4 · Diagrama unifilar'}).click();
  await page.locator('#diagrama-wrap-toolbar [data-view="width"]').click();
  if(errors.length)throw Error(errors.join('\n'));
  return {summary,sourceRows:'Hoja1!5–Hoja1!23',clippedText:0,pageErrors:errors.length,downloads:2,upsSwitch:true,backupToggle:true};
}
